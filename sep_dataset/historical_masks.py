"""Recover pre-imputation historical availability without shipping measurements."""
from __future__ import annotations

import base64
import gzip
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd

from .compatible_baseline import FEATURES, window_columns
from .cleaned_builder import SOURCE_FILL_VALUES

SCHEMA = "sep-original-availability-v2"
DEFAULT_BUNDLE = Path(__file__).resolve().parents[1] / "calibration" / "historical_raw_masks.json.gz"


def _keys(frame):
    if not {"FlrOnset", "event_type"}.issubset(frame):
        raise ValueError("Historical availability requires FlrOnset and event_type")
    dates = pd.to_datetime(frame.FlrOnset, utc=True, format="mixed", errors="raise")
    if dates.isna().any():
        raise ValueError("Historical flare onsets cannot be missing")
    labels = pd.to_numeric(frame.event_type, errors="coerce")
    if not labels.isin([0, 1]).all():
        raise ValueError("Historical labels must be binary")
    return dates.astype("datetime64[ns, UTC]").astype(str) + "|" + labels.astype(int).astype(str)


def _missing(x, feature):
    bad = ~np.isfinite(x) | (x == -99999) | (x == -9999) | (np.abs(x) >= 1e29)
    # The original XRS files also contain large negative values generated by
    # averaging a missing sentinel with valid samples. Unsigned physical
    # features cannot use negative values as interpolation anchors. Signed Vx
    # and valid zero measurements are explicitly preserved.
    if feature in FEATURES and feature != "Vx":
        bad |= x < 0
    if feature in SOURCE_FILL_VALUES:
        fill = SOURCE_FILL_VALUES[feature]
        bad |= (x == fill) | (x == float(np.float32(fill)))
    return bad


def anchor_digest(x, missing):
    """Verify source precision while ignoring binary64 CSV spelling tails.

    Historical flow-speed averages can lie exactly halfway between float32
    numbers. A binary64 CSV spelling change near 1e-16 relative can then flip
    the float32 rounding tie. Canonicalize to twelve significant decimal digits
    before float32 conversion; actual supplied values are never rewritten.
    """
    values = np.asarray(x[~missing], dtype=float).copy()
    if not np.isfinite(values).all():
        raise ValueError("Nonfinite values cannot be verified as observed anchors")
    nonzero = values != 0
    exponents = np.zeros(len(values), dtype=int)
    exponents[nonzero] = np.floor(np.log10(np.abs(values[nonzero]))).astype(int)
    for exponent in np.unique(exponents[nonzero]):
        selected = nonzero & (exponents == exponent)
        values[selected] = np.round(values[selected], decimals=max(-300, min(300, 11 - int(exponent))))
    values = np.asarray(values, dtype="<f4")
    values[values == 0] = 0
    return hashlib.sha256(values.tobytes(order="C")).hexdigest()


def build_mask_bundle(raw_dir, bundle_path=DEFAULT_BUNDLE):
    raw_dir, bundle_path = Path(raw_dir), Path(bundle_path)
    keys, records = None, {}
    for feature in FEATURES:
        found = list(raw_dir.rglob(f"1998_2013_MEMSEP_dataset_with_{feature}.csv"))
        if len(found) != 1:
            raise ValueError(f"Expected exactly one ORIGINAL UNFILLED {feature} file in {raw_dir}")
        path = found[0]
        frame = pd.read_csv(path, float_precision="round_trip", low_memory=False)
        current = _keys(frame).tolist()
        if keys is None:
            keys = current
            if len(set(keys)) != len(keys):
                raise ValueError("Original historical sample keys are not unique")
        elif current != keys:
            raise ValueError(f"Original historical identities differ: {feature}")
        x = frame[window_columns(feature)].to_numpy(dtype=float)
        missing = _missing(x, feature)
        records[feature] = {
            "shape": list(missing.shape), "missing_bits": base64.b64encode(np.packbits(missing).tobytes()).decode(),
            "observed_anchor_sha256_float32": anchor_digest(x, missing),
            "raw_file_sha256": hashlib.sha256(path.read_bytes()).hexdigest(), "raw_filename": path.name,
            "wholly_unavailable_rows": int(missing.all(axis=1).sum()), "missing_points": int(missing.sum()),
        }
    data = {"schema": SCHEMA, "keys": keys, "features": records,
            "missing_policy": "Nonfinite, -99999/-9999, large CDF-style fill magnitudes, documented positive OMNI fills and negative unsigned-feature values; zero and signed Vx remain valid.",
            "precision": "Observed anchors verified after twelve-significant-decimal-digit CSV canonicalization followed by little-endian float32 conversion; supplied observations are not changed; no flux values stored in this bundle."}
    payload = gzip.compress(json.dumps(data, sort_keys=True, separators=(",", ":")).encode(), mtime=0)
    bundle_path.parent.mkdir(parents=True, exist_ok=True)
    bundle_path.write_bytes(payload)
    manifest = {"schema": SCHEMA, "bundle_sha256": hashlib.sha256(payload).hexdigest(), "historical_rows": len(keys),
                "precision": data["precision"], "missing_policy": data["missing_policy"],
                "features": {f: {k: v for k, v in r.items() if k != "missing_bits"} for f, r in records.items()}}
    bundle_path.with_suffix(".manifest.json").write_text(json.dumps(manifest, indent=2)+"\n")
    return manifest


def load_mask_bundle(bundle_path=None):
    path = Path(bundle_path or DEFAULT_BUNDLE)
    manifest_path = path.with_suffix(".manifest.json")
    if not path.is_file() or not manifest_path.is_file():
        raise FileNotFoundError(
            f"Historical availability requires {path} and {manifest_path}. "
            "Unpack the historical availability ZIP in the project folder or generate the bundle "
            "with scripts/build_historical_masks.py from the ten original unfilled CSVs."
        )
    manifest = json.loads(manifest_path.read_text())
    payload = path.read_bytes()
    if hashlib.sha256(payload).hexdigest() != manifest["bundle_sha256"]:
        raise ValueError("Historical raw-mask checksum mismatch")
    data = json.loads(gzip.decompress(payload))
    if (data.get("schema") != SCHEMA or manifest.get("schema") != SCHEMA
            or set(data.get("features", {})) != set(FEATURES)):
        raise ValueError("Unsupported historical availability bundle")
    if len(set(data["keys"])) != len(data["keys"]):
        raise ValueError("Historical availability keys are not unique")
    if manifest.get("historical_rows") != len(data["keys"]):
        raise ValueError("Historical availability row count disagrees with manifest")
    for feature in FEATURES:
        record = data["features"][feature]
        if record.get("shape") != [len(data["keys"]), 288]:
            raise ValueError(f"Historical availability mask shape is invalid: {feature}")
        expected = {k: v for k, v in record.items() if k != "missing_bits"}
        if manifest.get("features", {}).get(feature) != expected:
            raise ValueError(f"Historical availability record disagrees with manifest: {feature}")
        try:
            bits = base64.b64decode(record["missing_bits"], validate=True)
        except (ValueError, TypeError) as exc:
            raise ValueError(f"Invalid packed historical availability mask: {feature}") from exc
        if len(bits) != len(data["keys"]) * 36:
            raise ValueError(f"Wrong packed historical availability length: {feature}")
        missing = np.unpackbits(np.frombuffer(bits, dtype=np.uint8)).reshape(record["shape"])
        if (int(missing.sum()) != record["missing_points"]
                or int(missing.all(axis=1).sum()) != record["wholly_unavailable_rows"]):
            raise ValueError(f"Historical availability counts disagree: {feature}")
    data["bundle_sha256"] = manifest["bundle_sha256"]
    return data


def apply_historical_masks(frame, quality, feature, bundle):
    if feature not in FEATURES or feature not in bundle.get("features", {}):
        raise ValueError(f"No original historical availability mask for feature: {feature}")
    if len(frame) != len(quality) or "point_status" not in quality:
        raise ValueError("Historical quality rows must align with the full feature dataset")
    if not frame.index.is_unique or not quality.index.is_unique:
        raise ValueError("Feature and quality row indexes must be unique")
    if "row_index" in quality and quality.row_index.tolist() != list(range(len(frame))):
        raise ValueError("Historical quality row_index does not match feature positions")
    frame, quality = frame.copy(), quality.copy()
    dates = pd.to_datetime(frame.FlrOnset, utc=True, format="mixed")
    positions = np.flatnonzero(dates.le(pd.Timestamp("2014-01-01", tz="UTC")-pd.Timedelta(nanoseconds=1)))
    keys = _keys(frame.iloc[positions]).tolist()
    expected = bundle["keys"]
    if len(keys) != len(expected) or set(keys) != set(expected):
        raise ValueError("Repair needs the complete unfiltered historical cohort; raw mask identities do not match")
    lookup = {key: row for row, key in enumerate(keys)}
    order = np.array([lookup[key] for key in expected])
    record = bundle["features"][feature]
    mask = np.unpackbits(np.frombuffer(base64.b64decode(record["missing_bits"]), dtype=np.uint8))
    mask = mask[:np.prod(record["shape"])].reshape(record["shape"]).astype(bool)
    values = frame.iloc[positions][window_columns(feature)].to_numpy(dtype=float)
    if anchor_digest(values[order], mask) != record["observed_anchor_sha256_float32"]:
        raise ValueError(f"Historical observed anchors disagree with the original raw files: {feature}")
    source_mask = mask[np.argsort(order)]
    strings = quality.iloc[positions].point_status.astype(str)
    if not strings.str.fullmatch("[OIEMDHSGU]{288}").all():
        raise ValueError("Historical quality point-status masks must contain 288 recognized codes")
    values[source_mask] = -9999.0
    frame.loc[frame.index[positions], window_columns(feature)] = values
    statuses = np.array([list(str(value)) for value in quality.iloc[positions].point_status], dtype="U1")
    statuses[source_mask] = "G"
    quality.loc[quality.index[positions], "point_status"] = ["".join(row) for row in statuses]
    if "historical_raw_missing_points" not in quality:
        quality["historical_raw_missing_points"] = 0
    quality.loc[quality.index[positions], "historical_raw_missing_points"] = source_mask.sum(axis=1)
    if "historical_raw_mask_applied" not in quality:
        quality["historical_raw_mask_applied"] = False
    quality.loc[quality.index[positions], "historical_raw_mask_applied"] = True
    if "missing_points_after" in quality:
        quality.loc[quality.index[positions], "missing_points_after"] = np.isin(statuses, ["S", "G"]).sum(axis=1)
    if "structural_missing_points" in quality:
        quality.loc[quality.index[positions], "structural_missing_points"] = (statuses == "S").sum(axis=1)
    return frame, quality, {"feature": feature, "historical_rows": len(positions),
                            "restored_missing_points": int(source_mask.sum()),
                            "wholly_unavailable_rows": int(source_mask.all(axis=1).sum()),
                            "original_raw_sha256": record["raw_file_sha256"],
                            "observed_anchor_hash_verified": True,
                            "availability_bundle_sha256": bundle.get("bundle_sha256")}
